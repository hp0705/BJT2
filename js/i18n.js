export function t(key, vars = {}) {
  const lang = loadState().settings.lang || 'vi';
  let str = (DICT[lang] && DICT[lang][key]) || DICT.vi[key] || key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(`{${k}}`, String(v));
  }
  return str;
}
